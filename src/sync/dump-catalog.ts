import Database from "better-sqlite3";

/**
 * Tables the OFFLINE SCAN owns and may fully replace on every sync. The live
 * Worker never writes these, so a DELETE + reload is safe and idempotent.
 */
export const SCAN_OWNED_TABLES = [
  "scanner_runs",
  "brands",
  "assets",
  "manual_overrides",
] as const;

/**
 * Tables the LIVE BOT owns at runtime. The sync must never touch them:
 *   - `deliveries`      is the audit log (source of truth, append-only).
 *   - `generated_outputs` is the render cache.
 * Wiping them during a catalog sync would destroy audit history.
 */
export const RUNTIME_OWNED_TABLES = ["deliveries", "generated_outputs"] as const;

type Row = Record<string, unknown>;

/** SQLite literal for a single value, matching `sqlite3 .mode insert` output. */
function sqlLiteral(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    return Number.isFinite(value) ? String(value) : "NULL";
  }
  if (typeof value === "bigint") return value.toString();
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value instanceof Uint8Array || Buffer.isBuffer(value)) {
    const hex = Buffer.from(value as Uint8Array).toString("hex");
    return `X'${hex}'`;
  }
  // Text: single-quote escape, exactly like SQLite's own quoting.
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertStatement(table: string, columns: string[], row: Row): string {
  const cols = columns.map((c) => `"${c}"`).join(", ");
  const vals = columns.map((c) => sqlLiteral(row[c])).join(", ");
  return `INSERT INTO "${table}" (${cols}) VALUES (${vals});`;
}

/**
 * Build a D1-safe, DATA-ONLY sync script from a local SQLite catalog.
 *
 * The remote schema is owned by `wrangler d1 migrations` — this script emits NO
 * DDL. For each scan-owned table it does `DELETE FROM` then re-inserts every
 * row, so running it against a remote D1 produces exactly the local scan state
 * and is safe to re-run.
 *
 * No explicit BEGIN/COMMIT: `wrangler d1 execute` sends the whole file as one
 * batch, which D1 already applies atomically, and the remote D1 HTTP exec
 * endpoint rejects explicit `BEGIN TRANSACTION`/`SAVEPOINT` statements outright
 * ("use state.storage.transaction() instead") — this was only ever exercised
 * against local D1 (plain SQLite, no such restriction) until the first real
 * `--remote` run surfaced it.
 *
 * Delete order is child→parent (assets refs brands/scanner_runs); insert order
 * is parent→child, so foreign keys never dangle mid-batch.
 */
export function buildSyncSql(db: Database.Database): string {
  const lines: string[] = [];
  lines.push("-- logos-bot catalog sync — generated by src/sync/dump-catalog.ts");
  lines.push("-- DATA ONLY. Remote schema is managed by wrangler d1 migrations.");
  lines.push("-- Idempotent: resets scan-owned tables then reloads them.");
  lines.push("PRAGMA defer_foreign_keys = TRUE;");

  // Reset child→parent so FK references are cleared before their targets.
  for (const table of [...SCAN_OWNED_TABLES].reverse()) {
    lines.push(`DELETE FROM "${table}";`);
  }

  // Reload parent→child.
  for (const table of SCAN_OWNED_TABLES) {
    const columns = (
      db.prepare(`PRAGMA table_info(${table})`).all() as { name: string }[]
    ).map((c) => c.name);
    if (columns.length === 0) {
      throw new Error(`Table "${table}" not found in local catalog — is the scan db migrated?`);
    }
    const rows = db.prepare(`SELECT * FROM "${table}"`).all() as Row[];
    if (rows.length === 0) continue;
    lines.push(`-- ${table}: ${rows.length} row(s)`);
    for (const row of rows) {
      lines.push(insertStatement(table, columns, row));
    }
  }

  lines.push("");
  return lines.join("\n");
}
